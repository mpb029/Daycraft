"""Prepare user-supplied Meshy OBJ archives without remeshing or changing textures.

Usage: python3 verification/prepare-maccas-models.py /absolute/source-directory
The source directory contains ronald/, grimace/, hamburglar/, birdie/ with OBJ,
MTL and PNG files. Runtime geometry is indexed and preserves source UV seams.
"""
from pathlib import Path
import base64, hashlib, json, math, shutil, struct, sys

source = Path(sys.argv[1])
target = Path(__file__).resolve().parents[1] / 'assets/cinema/models'
target.mkdir(parents=True, exist_ok=True)
manifest = {'source': 'User-supplied Meshy OBJ exports, 15 October 2026',
            'processing': 'No remeshing. Valid source normals, UVs and PNG textures retained; zero normals repaired from neighbouring triangles. Geometry centered in X/Z with feet at Y=0 and normalized to height 1; runtime placement sets size.',
            'models': []}
for name in ['ronald', 'grimace', 'hamburglar', 'birdie']:
    folder = source / name
    obj = next(folder.glob('*.obj'))
    mtl = next(folder.glob('*.mtl'))
    texture_name = next(line.split(maxsplit=1)[1] for line in mtl.read_text().splitlines() if line.startswith('map_Kd '))
    texture = folder / texture_name
    positions, normals, uvs, faces = [], [], [], []
    for line in obj.read_text().splitlines():
        fields = line.split()
        if not fields: continue
        if fields[0] == 'v': positions.append(tuple(map(float, fields[1:4])))
        elif fields[0] == 'vn': normals.append(tuple(map(float, fields[1:4])))
        elif fields[0] == 'vt': uvs.append(tuple(map(float, fields[1:3])))
        elif fields[0] == 'f':
            face = [tuple(int(v) for v in f.split('/')) for f in fields[1:]]
            assert all(len(v) == 3 and all(k > 0 for k in v) for v in face)
            for i in range(1, len(face)-1): faces.extend([face[0], face[i], face[i+1]])
    lo = [min(p[i] for p in positions) for i in range(3)]
    hi = [max(p[i] for p in positions) for i in range(3)]
    origin = [(lo[0]+hi[0])/2, lo[1], (lo[2]+hi[2])/2]
    height = hi[1]-lo[1]
    # One supplied Ronald normal is zero. Recover only invalid normals from the
    # area-weighted neighbouring source triangles; retain every valid normal.
    face_normals = {}
    for i in range(0,len(faces),3):
        keys = faces[i:i+3]; a,b,c = [positions[k[0]-1] for k in keys]
        u = [b[j]-a[j] for j in range(3)]; v = [c[j]-a[j] for j in range(3)]
        cross = [u[1]*v[2]-u[2]*v[1],u[2]*v[0]-u[0]*v[2],u[0]*v[1]-u[1]*v[0]]
        for k in keys:
            acc = face_normals.setdefault(k[0],[0.,0.,0.])
            for j in range(3):acc[j] += cross[j]
    vertices, indices, lookup = [], [], {}
    repaired = 0
    for key in faces:
        if key not in lookup:
            lookup[key] = len(vertices)
            p = positions[key[0]-1]; n = normals[key[2]-1]; uv = uvs[key[1]-1]
            length = math.sqrt(sum(q*q for q in n))
            if length < .9:
                n = face_normals[key[0]]; length = math.sqrt(sum(q*q for q in n))
                n = tuple(q/length for q in n) if length > 1e-12 else (0.,1.,0.)
                repaired += 1
            assert all(math.isfinite(q) for q in (*p,*n,*uv))
            vertices.append((tuple((p[i]-origin[i])/height for i in range(3)), n, uv))
        indices.append(lookup[key])
    assert len(vertices) < 65536
    values = [v for a in range(3) for vertex in vertices for v in vertex[a]]
    packed = struct.pack('<'+'f'*len(values), *values) + struct.pack('<'+'H'*len(indices), *indices)
    bounds = [[(lo[i]-origin[i])/height, (hi[i]-origin[i])/height] for i in range(3)]
    data = {'id': name, 'vertexCount': len(vertices), 'indexCount': len(indices), 'bounds': bounds,
            'packed': base64.b64encode(packed).decode()}
    output = target / (name+'.mjs')
    output.write_text('// User-supplied Meshy model. See provenance.json. Generated by verification/prepare-maccas-models.py.\nexport default '+json.dumps(data,separators=(',',':'))+';\n')
    texture_target = target / (name+'-color.png')
    shutil.copyfile(texture, texture_target)
    record = {'id': name, 'sourceObj': obj.name, 'sourceObjSHA256': hashlib.sha256(obj.read_bytes()).hexdigest(),
              'texture': './assets/cinema/models/'+texture_target.name,
              'textureSHA256': hashlib.sha256(texture.read_bytes()).hexdigest(),
              'geometry': './assets/cinema/models/'+output.name,
              'geometrySHA256': hashlib.sha256(output.read_bytes()).hexdigest(),
              'vertices': len(vertices), 'triangles': len(indices)//3, 'bounds': bounds,'repairedZeroNormalVertices':repaired}
    manifest['models'].append(record)
    print(name, len(vertices), 'vertices,', len(indices)//3, 'triangles,',len(packed),'geometry bytes')
(target/'provenance.json').write_text(json.dumps(manifest,indent=2)+'\n')
